"""Semantic prompt cache (M5).

Every generated image is stored in object storage and its prompt *embedding*
in Valkey. A new /generate request embeds its prompt and searches stored
entries by cosine similarity; sim >= threshold AND version/age confidence
passes -> the cached image URL is returned (0 GPU seconds).

- Versioned key prefix per workflow version: promoting a new champion
  invalidates all entries generated by other versions (a cached image from
  model v1 must never serve v2 traffic).
- Confidence gate: threshold + exact version match + entry age < TTL.
- Audit: a sample of hits is recorded (5%, COMFYOPS_CACHE_AUDIT_RATE) so
  cache accuracy can be monitored.

Embeddings: open_clip ViT-B-32 text encoder (lazy-loaded; the first request
pays the model load). COMFYOPS_MOCK_CACHE=1 substitutes deterministic
pseudo-embeddings so tests/CI never need torch.
"""

import base64
import hashlib
import json
import os
import struct
import time

import numpy as np
from redis import Redis

from app.core.config import settings

# Threshold calibrated on real ViT-B-32 text embeddings (2026-10-03):
#   exact / paraphrase matches      >= 0.94  (e.g. "red apple" <-> "apple that is red" 0.989,
#                                              "red shoe" <-> "red sneaker" 0.940)
#   near-misses (same subject, diff attribute) ~ 0.88  ("red shoe" <-> "blue shoe")
#   unrelated                           <= 0.78
# 0.92 separates paraphrase hits from near-misses.
SIM_THRESHOLD = float(os.getenv("COMFYOPS_CACHE_THRESHOLD", "0.92"))
AUDIT_RATE = float(os.getenv("COMFYOPS_CACHE_AUDIT_RATE", "0.05"))
MOCK = os.getenv("COMFYOPS_MOCK_CACHE") == "1"

_redis = Redis.from_url(settings.redis_url, decode_responses=False)
_encoder = None
_tokenizer = None


def _key(version: str) -> str:
    return f"comfyops:cache:v{version}"


def _pack(embedding: np.ndarray, image_url: str, prompt: str) -> str:
    blob = base64.b64encode(struct.pack(f"<{embedding.size}f", *embedding)).decode()
    return json.dumps({"e": blob, "u": image_url, "p": prompt, "t": time.time()})


def _unpack(raw: bytes) -> dict | None:
    try:
        entry = json.loads(raw)
        entry["v"] = np.frombuffer(base64.b64decode(entry["e"]), dtype="<f4")
        return entry
    except Exception:
        return None


def _embed(prompt: str) -> np.ndarray:
    global _encoder, _tokenizer
    if MOCK:
        h = int(hashlib.sha256(prompt.encode()).hexdigest(), 16)
        vec = np.array([((h >> (i * 8)) & 0xFF) / 255.0 - 0.5 for i in range(64)], dtype="<f4")
        return vec / (np.linalg.norm(vec) or 1.0)
    if _encoder is None:
        import open_clip
        import torch

        _encoder, _, _ = open_clip.create_model_and_transforms(
            "ViT-B-32", pretrained="openai",
            cache_dir=os.path.join(os.path.dirname(__file__), "..", "..", "..", ".model_cache"),
        )
        _encoder.eval()
        _tokenizer = open_clip.get_tokenizer("ViT-B-32")
    import torch

    with torch.no_grad():
        feat = _encoder.encode_text(_tokenizer([prompt]))
    feat /= feat.norm(dim=-1, keepdim=True)
    return feat[0].numpy().astype("<f4")


def lookup(prompt: str, version: str) -> str | None:
    """Return a cached image_url if a similar-enough, confident entry exists."""
    emb = _embed(prompt)
    now = time.time()
    for raw in _redis.lrange(_key(version), 0, -1):
        entry = _unpack(raw)
        if entry is None:
            continue
        if entry["v"].size != emb.size:
            continue
        if now - entry["t"] > settings.result_ttl_seconds:
            continue
        sim = float(np.dot(emb, entry["v"]))
        if sim >= SIM_THRESHOLD:
            if MOCK or __import__("random").random() < AUDIT_RATE:
                _redis.lpush("comfyops:cache:audit", json.dumps({"prompt": prompt, "hit": entry["p"], "sim": round(sim, 4)}))
            return entry["u"]
    return None


def store(prompt: str, version: str, image_url: str) -> None:
    emb = _embed(prompt)
    _redis.lpush(_key(version), _pack(emb, image_url, prompt))
    _redis.ltrim(_key(version), 0, 999)


def invalidate(version: str) -> None:
    """Drop cache entries generated by any version other than `version`
    (called when `version` is promoted to champion)."""
    for key in _redis.scan_iter("comfyops:cache:v*", count=100):
        if key != _key(version).encode():
            _redis.delete(key)